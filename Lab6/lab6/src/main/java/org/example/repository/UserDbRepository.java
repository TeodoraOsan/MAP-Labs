package org.example.repository;

import org.example.domain.User;
import org.example.domain.exception.RepositoryException;
import org.example.domain.validator.Validator;
import org.example.util.paging.Page;
import org.example.util.paging.Pageable;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Repository implementation for persisting {@link User} entities in a PostgreSQL database using JDBC.
 */
public class UserDbRepository implements PagingRepository<Long, User> {
    private final Validator<User> validator;
    private final String url;
    private final String username;
    private final String password;

    /**
     * Constructs a new UserDbRepository with connection parameters and validator.
     *
     * @param validator the entity validator
     * @param url       the database connection URL
     * @param username  the database username
     * @param password  the database password
     */
    public UserDbRepository(Validator<User> validator, String url, String username, String password) {
        this.validator = validator;
        this.url = url;
        this.username = username;
        this.password = password;
    }

    /**
     * Finds a user by their identifier.
     * @param id the identifier of the user to be found
     * @return an {@link Optional} containing the found user, or {@link Optional#empty()} if no user was found
     * @throws IllegalArgumentException if the provided id is null
     * @throws RepositoryException      if a database access error occurs
     */
    @Override
    public Optional<User> findOne(Long id) {
        if (id == null) {
            throw new IllegalArgumentException("ID must not be null!");
        }
        String sql = "SELECT * FROM users WHERE id = ?";
        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    String firstName = resultSet.getString("first_name");
                    String lastName = resultSet.getString("last_name");
                    User user = new User(firstName, lastName);
                    user.setId(id);
                    return Optional.of(user);
                }
            }
        } catch (SQLException e) {
            throw new RepositoryException("Database error: " + e.getMessage(), e);
        }
        return Optional.empty();
    }

    /**
     * Retrieves all users from the database.
     * @return a {@link List} containing all users stored in the database
     * @throws RepositoryException if a database access error occurs
     */
    @Override
    public List<User> findAll() {
        List<User> users = new ArrayList<>();
        String sql = "SELECT * FROM users";

        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {

            while (resultSet.next()) {
                Long id = resultSet.getLong("id");
                String firstName = resultSet.getString("first_name");
                String lastName = resultSet.getString("last_name");

                User user = new User(firstName, lastName);
                user.setId(id);
                users.add(user);
            }
        } catch (SQLException e) {
            throw new RepositoryException("Database error: " + e.getMessage(), e);
        }
        return users;
    }

    /**
     * Saves a given user to the database.
     * If the save operation is successful, the ID generated by the database is assigned to the entity.
     * @param entity the user to be saved
     * @return null if the entity was saved successfully
     * @throws IllegalArgumentException if the entity is null
     * @throws org.example.domain.exception.ValidationException if the entity is not valid
     * @throws RepositoryException      if a database access error occurs or the save operation fails
     */
    @Override
    public User save(User entity) {
        if (entity == null) {
            throw new IllegalArgumentException("Entity must not be null!");
        }
        validator.validate(entity);

        String sql = "INSERT INTO users (first_name, last_name) VALUES (?, ?)";

        try (Connection connection = DriverManager.getConnection(url, username, password);
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            statement.setString(1, entity.getFirstName());
            statement.setString(2, entity.getLastName());

            int affectedRows = statement.executeUpdate();
            if (affectedRows == 0) {
                throw new RepositoryException("User save failed!");
            }

            try (ResultSet generatedKeys = statement.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    entity.setId(generatedKeys.getLong(1));
                }
            }
            return null;

        } catch (SQLException e) {
            throw new RepositoryException("Database error: " + e.getMessage(), e);
        }
    }

    /**
     * Deletes a user by their identifier.
     * @param id the identifier of the user to be deleted
     * @return an {@link Optional} containing the deleted user, or {@link Optional#empty()} if no user was found
     * @throws IllegalArgumentException if the provided id is null
     * @throws RepositoryException      if a database access error occurs
     */
    @Override
    public Optional<User> delete(Long id) {
        if (id == null) {
            throw new IllegalArgumentException("ID must not be null!");
        }
        Optional<User> userToDelete = findOne(id);

        if (userToDelete.isPresent()) {
            String sql = "DELETE FROM users WHERE id = ?";
            try (Connection connection = DriverManager.getConnection(url, username, password);
                 PreparedStatement statement = connection.prepareStatement(sql)) {

                statement.setLong(1, id);
                statement.executeUpdate();

            } catch (SQLException e) {
                throw new RepositoryException("Database error: " + e.getMessage(), e);
            }
        }
        return userToDelete;
    }

    /**
     * Retrieves a page of users ordered by their ID.
     * @param pageable pagination parameters
     * @return a Page of users
     * @throws IllegalArgumentException if pageNumber < 0 or pageSize <= 0
     */
    @Override
    public Page<User> findAllOnPage(Pageable pageable) {
        if (pageable == null || pageable.getPageNumber() < 0 || pageable.getPageSize() <= 0) {
            throw new IllegalArgumentException("Invalid pagination parameters: pageNumber must be >= 0 and pageSize > 0");
        }

        List<User> users = new ArrayList<>();
        int totalCount = 0;

        String countSql = "SELECT COUNT(*) AS count FROM users";
        String pageSql = "SELECT * FROM users ORDER BY id LIMIT ? OFFSET ?";

        try (Connection connection = DriverManager.getConnection(url, username, password)) {
            try (PreparedStatement countStmt = connection.prepareStatement(countSql);
                 ResultSet countRs = countStmt.executeQuery()) {
                if (countRs.next()) {
                    totalCount = countRs.getInt("count");
                }
            }

            try (PreparedStatement pageStmt = connection.prepareStatement(pageSql)) {
                pageStmt.setInt(1, pageable.getPageSize());
                pageStmt.setInt(2, pageable.getPageNumber() * pageable.getPageSize());

                try (ResultSet rs = pageStmt.executeQuery()) {
                    while (rs.next()) {
                        users.add(extractUser(rs));
                    }
                }
            }
        } catch (SQLException e) {
            throw new RepositoryException("Database error while fetching paged users", e);
        }
        return new Page<>(users, totalCount);
    }

    private User extractUser(ResultSet rs) throws SQLException {
        Long id = rs.getLong("id");
        String firstName = rs.getString("first_name");
        String lastName = rs.getString("last_name");
        User user = new User(firstName, lastName);
        user.setId(id);
        return user;
    }
}
